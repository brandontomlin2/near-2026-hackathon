#!/usr/bin/env node
// Generates docs/yield-live-dry-run-transcript.md from the real `yield-live dry-run` code path.
//
//   node scripts/yield-live-transcript.mjs                write the transcript
//   node scripts/yield-live-transcript.mjs --check        exit 1 when the committed file differs
//   node scripts/yield-live-transcript.mjs --file PATH    use PATH instead of the committed file
//
// main() from scripts/yield-live.mjs runs in-process with captured output, an EMPTY env object and a
// pinned clock. Nothing is signed or sent, no process env is read, no child process is started.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { main } from "./yield-live.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const TRANSCRIPT_FILE = resolve(ROOT, "docs/yield-live-dry-run-transcript.md");
const SNAPSHOT_FILE = resolve(ROOT, "src/yield/fixtures/ref-testnet-pools.json");
const HOUR_MS = 3_600_000;

export const SNAPSHOT_TAKEN_AT = JSON.parse(readFileSync(SNAPSHOT_FILE, "utf8"))._taken_at;
/** The snapshot's _taken_at plus exactly 24 h, derived from the fixture. */
export const TRANSCRIPT_NOW = Date.parse(SNAPSHOT_TAKEN_AT) + 24 * HOUR_MS;

export const RUNS = Object.freeze([
  { title: "1. Full dry-run", command: "npm run yield:live:dry-run", argv: ["dry-run"], showStdout: true },
  { title: "2. Dry-run with --require-ready", command: "npm run yield:live:dry-run -- --require-ready", argv: ["dry-run", "--require-ready"], showStdout: false },
  { title: "3. Dry-run with --send", command: "npm run yield:live:dry-run -- --send", argv: ["dry-run", "--send"], showStdout: true },
]);

async function capture(argv) {
  const out = [];
  const errs = [];
  const code = await main(argv, { log: (...a) => out.push(a.join(" ")), err: (s) => errs.push(s), env: {}, now: () => TRANSCRIPT_NOW });
  return { code, stdout: out.join("\n"), stderr: errs.join("\n") };
}

const fence = (text) => ["```text", ...(text === "" ? [] : [text]), "```"].join("\n");

export async function renderTranscript() {
  const parts = [
    "# Yield vault live dry-run transcript",
    "",
    `This file is generated by \`node scripts/yield-live-transcript.mjs\`; do not edit it by hand. It is the real output of \`scripts/yield-live.mjs\` (the \`main\` function, called in-process), captured with an empty env object so no environment value is read or printed, and nothing is signed or sent. The clock is pinned to ${new Date(TRANSCRIPT_NOW).toISOString().replace(".000Z", "Z")}, exactly 24 h after the pool snapshot's \`_taken_at\` (${SNAPSHOT_TAKEN_AT}), so the "snapshot age" row reads fresh and the text does not change as wall time passes; a real run prints the age at the moment you run it. The human output does not depend on whether a built wasm exists (the wasm path is printed from the config, and the wasm size and sha256 appear only in the \`--json\` document and in \`preflight\`). \`node --test scripts/yield-live-transcript.test.mjs\` fails when this file no longer matches what the command prints; regenerate it with the command above.`,
  ];
  for (const run of RUNS) {
    const r = await capture(run.argv);
    parts.push("", `## ${run.title}`, "", `Command: \`${run.command}\``, "", `Exit code: ${r.code}`);
    if (run.showStdout) parts.push("", "stdout:", "", fence(r.stdout));
    else parts.push("", "stdout: identical to run 1, not repeated.");
    parts.push("", "stderr:", "", fence(r.stderr));
  }
  return `${parts.join("\n")}\n`;
}

/** null when equal, else a short description of the first differing line. */
export function firstDifference(expected, actual) {
  if (expected === actual) return null;
  const a = expected.split("\n");
  const b = actual.split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) return `line ${i + 1}: generated ${JSON.stringify(a[i] ?? "(end of file)")} vs file ${JSON.stringify(b[i] ?? "(end of file)")}`;
  }
  return "files differ";
}

export async function cli(argv, { log = console.log, err = console.error } = {}) {
  let file = TRANSCRIPT_FILE;
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") check = true;
    else if (argv[i] === "--file" && argv[i + 1] !== undefined) file = resolve(argv[++i]);
    else {
      err(`usage: node scripts/yield-live-transcript.mjs [--check] [--file PATH]`);
      return 2;
    }
  }
  const text = await renderTranscript();
  if (check) {
    let current;
    try {
      current = readFileSync(file, "utf8");
    } catch (e) {
      err(`transcript ${file} cannot be read (${e.code ?? e.message}); run: node scripts/yield-live-transcript.mjs`);
      return 1;
    }
    const diff = firstDifference(text, current);
    if (diff) {
      err(`transcript out of date, ${diff}; run: node scripts/yield-live-transcript.mjs`);
      return 1;
    }
    log("transcript up to date");
    return 0;
  }
  writeFileSync(file, text);
  log(`wrote ${file}`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  cli(process.argv.slice(2)).then((code) => {
    process.exitCode = code;
  });
}
